using System.Text;
using CSJS.Core.Mapping;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CSJS.Core.Emit;

/// <summary>
/// Emits the TypeScript declaration file for a transpiled module.
/// <para>
/// This is the half of the type-safety layer that faces outward: C#'s type information would
/// otherwise be erased at the JavaScript boundary, and a <c>.d.ts</c> is what lets TypeScript
/// consumers keep it. It reads the same <see cref="TypeMap"/> the expression emitter uses, so a
/// declared signature and the code implementing it cannot drift apart.
/// </para>
/// </summary>
public sealed class DtsEmitter
{
    private readonly SemanticModel _model;
    private readonly NameResolver _names;
    private readonly StringBuilder _sb = new();
    private int _depth;

    public DtsEmitter(SemanticModel model, NameResolver names)
    {
        _model = model;
        _names = names;
    }

    public string Emit(CompilationUnitSyntax unit, string moduleName)
    {
        Line($"// Type declarations for {moduleName}, generated by CSJS.");
        Line("// Gravicode Studios — led by Kang Fadhil.");
        Line();

        foreach (var declaration in CollectTypes(unit))
        {
            switch (declaration)
            {
                case EnumDeclarationSyntax enumDecl: EmitEnum(enumDecl); break;
                case InterfaceDeclarationSyntax interfaceDecl: EmitInterface(interfaceDecl); break;
                case TypeDeclarationSyntax typeDecl: EmitClass(typeDecl); break;
            }
        }

        return _sb.ToString();
    }

    private static IEnumerable<MemberDeclarationSyntax> CollectTypes(SyntaxNode root)
    {
        foreach (var member in root.ChildNodes().OfType<MemberDeclarationSyntax>())
        {
            switch (member)
            {
                case BaseNamespaceDeclarationSyntax ns:
                    foreach (var nested in CollectTypes(ns)) yield return nested;
                    break;
                case TypeDeclarationSyntax or EnumDeclarationSyntax:
                    yield return member;
                    break;
            }
        }
    }

    private void EmitEnum(EnumDeclarationSyntax declaration)
    {
        var symbol = _model.GetDeclaredSymbol(declaration) as INamedTypeSymbol;
        if (symbol is null || !IsExported(symbol)) return;

        var name = _names.TypeName(symbol);
        EmitDoc(declaration);

        // The emitted value is a frozen object with a reverse map, so the declaration has to
        // describe both directions to stay honest about what is actually there.
        Line($"export declare const {name}: {{");
        _depth++;
        foreach (var member in declaration.Members)
        {
            var value = (_model.GetDeclaredSymbol(member) as IFieldSymbol)?.ConstantValue;
            Line($"readonly {member.Identifier.Text}: {value ?? 0};");
        }
        Line("readonly [ordinal: number]: string;");
        _depth--;
        Line("};");
        Line();

        Line($"export type {name} = typeof {name}[keyof typeof {name}];");
        Line();
    }

    private void EmitInterface(InterfaceDeclarationSyntax declaration)
    {
        var symbol = _model.GetDeclaredSymbol(declaration) as INamedTypeSymbol;
        if (symbol is null || !IsExported(symbol)) return;

        EmitDoc(declaration);
        Line($"export interface {_names.TypeName(symbol)}{TypeParameters(symbol)}{BaseList(symbol, "extends")} {{");
        _depth++;
        EmitMemberSignatures(symbol, includeStatics: false, isInterface: true);
        _depth--;
        Line("}");
        Line();
    }

    private void EmitClass(TypeDeclarationSyntax declaration)
    {
        var symbol = _model.GetDeclaredSymbol(declaration) as INamedTypeSymbol;
        if (symbol is null || !IsExported(symbol)) return;
        if (JsEmitter.HasAttribute(symbol, "JsIgnoreAttribute")) return;
        if (NameResolver.JsGlobalName(symbol) is not null) return;

        EmitDoc(declaration);

        var baseClause = symbol.BaseType is { SpecialType: not SpecialType.System_Object, TypeKind: TypeKind.Class } baseType
            ? $" extends {_names.TypeName(baseType)}"
            : "";

        // Only interfaces declared in this compilation exist in the emitted .d.ts. Compiler-
        // supplied ones such as IEquatable<T> on a record would be dangling references.
        var interfaces = DeclaredInterfaces(symbol);
        var implementsClause = interfaces.Count > 0
            ? $" implements {string.Join(", ", interfaces.Select(i => _names.TypeName(i)))}"
            : "";

        Line($"export declare class {_names.TypeName(symbol)}{TypeParameters(symbol)}{baseClause}{implementsClause} {{");
        _depth++;
        EmitConstructors(symbol);
        EmitMemberSignatures(symbol, includeStatics: true, isInterface: false);
        _depth--;
        Line("}");
        Line();
    }

    private void EmitConstructors(INamedTypeSymbol symbol)
    {
        var constructors = symbol.InstanceConstructors
            .Where(c => c.DeclaredAccessibility == Accessibility.Public && !c.IsImplicitlyDeclared)
            .OrderBy(c => c.DeclaringSyntaxReferences.FirstOrDefault()?.Span.Start ?? 0)
            .ToList();

        for (var i = 0; i < constructors.Count; i++)
        {
            var ctor = constructors[i];
            // Only the first constructor stays a constructor; the rest became static factories.
            if (i == 0) Line($"constructor({Parameters(ctor)});");
            else Line($"static new${i}({Parameters(ctor)}): {_names.TypeName(symbol)};");
        }
    }

    private void EmitMemberSignatures(INamedTypeSymbol symbol, bool includeStatics, bool isInterface)
    {
        foreach (var member in symbol.GetMembers())
        {
            if (member.DeclaredAccessibility != Accessibility.Public) continue;
            if (member.IsImplicitlyDeclared) continue;
            if (JsEmitter.HasAttribute(member, "JsIgnoreAttribute")) continue;
            if (!includeStatics && member.IsStatic) continue;

            var prefix = member.IsStatic && !isInterface ? "static " : "";

            switch (member)
            {
                case IFieldSymbol field when field.ContainingType.TypeKind != TypeKind.Enum:
                    Line($"{prefix}{_names.MemberName(field)}: {TypeMap.ToTypeScript(field.Type)};");
                    break;

                case IPropertySymbol { IsIndexer: false } property:
                    var readOnly = property.SetMethod is null ? "readonly " : "";
                    Line($"{prefix}{readOnly}{_names.MemberName(property)}: {TypeMap.ToTypeScript(property.Type)};");
                    break;

                case IPropertySymbol { IsIndexer: true } indexer:
                    // A user-declared indexer is emitted as $get/$set, so that is what callers see.
                    Line($"$get({Parameters(indexer.GetMethod)}): {TypeMap.ToTypeScript(indexer.Type)};");
                    if (indexer.SetMethod is not null)
                        Line($"$set({Parameters(indexer.GetMethod)}, value: {TypeMap.ToTypeScript(indexer.Type)}): void;");
                    break;

                case IEventSymbol eventSymbol:
                    Line($"{prefix}{_names.MemberName(eventSymbol)}: Array<{TypeMap.ToTypeScript(eventSymbol.Type)}>;");
                    break;

                case IMethodSymbol { MethodKind: MethodKind.Ordinary } method:
                    var returnType = MethodReturnType(method);
                    Line($"{prefix}{_names.MemberName(method)}{TypeParameters(method)}({Parameters(method)}): {returnType};");
                    break;
            }
        }
    }

    private string MethodReturnType(IMethodSymbol method)
    {
        // An iterator emits a generator, whose declared type is not the C# IEnumerable<T>.
        if (method.ReturnType is INamedTypeSymbol { TypeArguments.Length: 1 } named
            && TypeMap.Unbound(named) == "System.Collections.Generic.IEnumerable"
            && IsIterator(method))
        {
            return $"Generator<{TypeMap.ToTypeScript(named.TypeArguments[0])}, void, unknown>";
        }

        return TypeMap.ToTypeScript(method.ReturnType);
    }

    private static bool IsIterator(IMethodSymbol method)
        => method.DeclaringSyntaxReferences
            .Select(r => r.GetSyntax())
            .OfType<MethodDeclarationSyntax>()
            .Any(m => m.Body?.DescendantNodes().Any(n => n is YieldStatementSyntax) == true);

    private string Parameters(IMethodSymbol? method)
    {
        if (method is null) return "";

        return string.Join(", ", method.Parameters.Select(p =>
        {
            var name = NameResolver.Escape(p.Name);
            var type = TypeMap.ToTypeScript(p.Type);

            if (p.IsParams) return $"...{name}: {type}";
            // An optional parameter carries a default in the emitted JavaScript, so `?` is right.
            if (p.HasExplicitDefaultValue) return $"{name}?: {type}";
            return $"{name}: {type}";
        }));
    }

    private static string TypeParameters(ISymbol symbol)
    {
        var parameters = symbol switch
        {
            INamedTypeSymbol type => type.TypeParameters,
            IMethodSymbol method => method.TypeParameters,
            _ => default,
        };

        if (parameters.IsDefaultOrEmpty) return "";
        return $"<{string.Join(", ", parameters.Select(p => p.Name))}>";
    }

    private string BaseList(INamedTypeSymbol symbol, string keyword)
    {
        var interfaces = DeclaredInterfaces(symbol);
        if (interfaces.Count == 0) return "";
        return $" {keyword} {string.Join(", ", interfaces.Select(i => _names.TypeName(i)))}";
    }

    private static List<INamedTypeSymbol> DeclaredInterfaces(INamedTypeSymbol symbol)
        => symbol.Interfaces
            .Where(i => i.DeclaredAccessibility == Accessibility.Public)
            .Where(i => i.DeclaringSyntaxReferences.Length > 0)
            .ToList();

    private static bool IsExported(INamedTypeSymbol symbol)
        => symbol.DeclaredAccessibility == Accessibility.Public
           || JsEmitter.HasAttribute(symbol, "JsExportAttribute");

    private void EmitDoc(SyntaxNode node)
    {
        var trivia = node.GetLeadingTrivia()
            .Select(t => t.GetStructure())
            .OfType<DocumentationCommentTriviaSyntax>()
            .FirstOrDefault();

        if (trivia is null) return;

        var summary = trivia.Content.OfType<XmlElementSyntax>()
            .FirstOrDefault(e => e.StartTag.Name.LocalName.Text == "summary");
        if (summary is null) return;

        var text = JsEmitter.FlattenDocText(summary.Content.ToFullString());
        if (text.Length == 0) return;
        Line($"/** {text} */");
    }

    private void Line(string text = "")
    {
        if (text.Length > 0) _sb.Append(new string(' ', _depth * 2));
        _sb.Append(text).Append('\n');
    }
}
